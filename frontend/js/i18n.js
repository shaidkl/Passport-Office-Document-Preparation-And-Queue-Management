    if (lower === 'reviewed') return this.t('status_reviewed', 'Reviewed');
    if (lower === 'inactive') return this.t('status_inactive', 'Inactive');
    if (lower === 'locked') return this.t('status_locked', 'Locked');
    if (lower === 'failed') return this.t('status_failed', 'Failed');
    if (lower === 'in progress' || lower === 'in_progress') return this.t('status_in_progress', 'In Progress');
    if (lower === 'not started' || lower === 'not_started') return this.t('status_not_started', 'Not Started');
    if (lower === 'action required' || lower === 'action_required') return this.t('status_action_required', 'Action Required');
    if (lower === 'payment required' || lower === 'payment_required') return this.t('status_payment_required', 'Payment Required');
    if (lower === 'payment initiated' || lower === 'payment_initiated') return this.t('status_payment_initiated', 'Payment Initiated');
    if (lower === 'pending verification' || lower === 'pending_verification') return this.t('status_pending_verification', 'Pending Verification');
    if (lower === 'pending review' || lower === 'pending_review') return this.t('status_pending_review', 'Pending Review');
    if (lower === 'waiting') return this.t('status_waiting', 'Waiting');
    if (lower === 'called') return this.t('status_called', 'Called');
    if (lower === 'serving') return this.t('status_serving', 'Serving');
    if (lower === 'skipped') return this.t('status_skipped', 'Skipped');
    if (lower === 'active') return this.t('status_active', 'ACTIVE');
    if (lower === 'expired') return this.t('status_expired', 'EXPIRED');
    if (lower.includes('payment') && lower.includes('pending')) return this.t('status_payment_pending', 'Payment Pending');
    if (lower.includes('payment') && lower.includes('verifi')) return this.t('status_payment_verified', 'Payment Verified');
    if (lower.includes('payment') && lower.includes('fail')) return this.t('status_payment_failed', 'Payment Failed');
